# Take a 3 input from the user
# perform the sum, sub, mul and div

a = int(input("Enter the value of a: "))
b = int(input("Enter the value of b: "))
c = int(input("Enter the value of c: "))

print("The sum of a, b and c is: ", a + b + c)
print("The difference of a, b and c is: ", a - b - c)
print("The product of a, b and c is: ", a * b * c)
print("The division of a, b and c is: ", a / b / c)

